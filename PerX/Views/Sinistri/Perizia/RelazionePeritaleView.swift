    private func caricaVersioniDaCoreData() {
        guard let perizia = perizia else { return }
        
        // Forza refresh del context per assicurarsi di avere i dati più recenti
        viewContext.refresh(perizia, mergeChanges: true)
        
        // Carica versioni per ogni campo
        let versioniRelazioneCD = perizia.versioniPerCampo("relazionePerizia")
        versioniRelazione = versioniRelazioneCD.map { $0.contenuto }
        if !versioniRelazione.isEmpty {
            // Trova l'indice della versione corrente (ultima o quella che corrisponde al contenuto)
            if let contenutoCorrente = perizia.relazionePerizia, !contenutoCorrente.isEmpty {
                if let indice = versioniRelazione.firstIndex(of: contenutoCorrente) {
                    indiceVersioneRelazione = indice
                } else {
                    indiceVersioneRelazione = versioniRelazione.count - 1
                }
            } else {
                indiceVersioneRelazione = versioniRelazione.count - 1
            }
        } else if !relazionePerizia.isEmpty {
            // Se non ci sono versioni salvate ma c'è contenuto, crea prima versione
            versioniRelazione = [relazionePerizia]
            indiceVersioneRelazione = 0
            salvaVersioneInCoreData(field: .relazione, valore: relazionePerizia)
        }
        
        let versioniNoteConclusiveCD = perizia.versioniPerCampo("noteConclusive")
        versioniNoteConclusive = versioniNoteConclusiveCD.map { $0.contenuto }
        if !versioniNoteConclusive.isEmpty {
            if let contenutoCorrente = perizia.noteConclusive, !contenutoCorrente.isEmpty {
                if let indice = versioniNoteConclusive.firstIndex(of: contenutoCorrente) {
                    indiceVersioneNoteConclusive = indice
                } else {
                    indiceVersioneNoteConclusive = versioniNoteConclusive.count - 1
                }
            } else {
                indiceVersioneNoteConclusive = versioniNoteConclusive.count - 1
            }
        } else if !noteConclusive.isEmpty {
            versioniNoteConclusive = [noteConclusive]
            indiceVersioneNoteConclusive = 0
            salvaVersioneInCoreData(field: .noteConclusive, valore: noteConclusive)
        }
        
        let versioniNoteRiservaCD = perizia.versioniPerCampo("noteRiserva")
        versioniNoteRiserva = versioniNoteRiservaCD.map { $0.contenuto }
        if !versioniNoteRiserva.isEmpty {
            if let contenutoCorrente = perizia.noteRiserva, !contenutoCorrente.isEmpty {
                if let indice = versioniNoteRiserva.firstIndex(of: contenutoCorrente) {
                    indiceVersioneNoteRiserva = indice
                } else {
                    indiceVersioneNoteRiserva = versioniNoteRiserva.count - 1
                }
            } else {
                indiceVersioneNoteRiserva = versioniNoteRiserva.count - 1
            }
        } else if !noteRiserva.isEmpty {
            versioniNoteRiserva = [noteRiserva]
            indiceVersioneNoteRiserva = 0
            salvaVersioneInCoreData(field: .noteRiserva, valore: noteRiserva)
        }
        
        let versioniNoteOsservazioniCD = perizia.versioniPerCampo("noteOsservazioni")
        versioniNoteOsservazioni = versioniNoteOsservazioniCD.map { $0.contenuto }
        if !versioniNoteOsservazioni.isEmpty {
            if let contenutoCorrente = perizia.noteOsservazioni, !contenutoCorrente.isEmpty {
                if let indice = versioniNoteOsservazioni.firstIndex(of: contenutoCorrente) {
                    indiceVersioneNoteOsservazioni = indice
                } else {
                    indiceVersioneNoteOsservazioni = versioniNoteOsservazioni.count - 1
                }
            } else {
                indiceVersioneNoteOsservazioni = versioniNoteOsservazioni.count - 1
            }
        } else if !noteOsservazioni.isEmpty {
            versioniNoteOsservazioni = [noteOsservazioni]
            indiceVersioneNoteOsservazioni = 0
            salvaVersioneInCoreData(field: .noteOsservazioni, valore: noteOsservazioni)
        }
    }
    
    private func salvaVersione(field: CampoVersione, valore: String) {
        guard let perizia = perizia else { return }
        
        // Controlla se è diversa dall'ultima versione
        let versioniArray: [String]
        let indiceCorrente: Int
        
        switch field {
        case .relazione:
            versioniArray = versioniRelazione
            indiceCorrente = indiceVersioneRelazione
        case .noteConclusive:
            versioniArray = versioniNoteConclusive
            indiceCorrente = indiceVersioneNoteConclusive
        case .noteRiserva:
            versioniArray = versioniNoteRiserva
            indiceCorrente = indiceVersioneNoteRiserva
        case .noteOsservazioni:
            versioniArray = versioniNoteOsservazioni
            indiceCorrente = indiceVersioneNoteOsservazioni
        }
        
        // Se è uguale all'ultima versione, non salvare
        if let ultima = versioniArray.last, ultima == valore {
            return
        }
        
        // Rimuovi versioni future se siamo in mezzo alla cronologia
        let versioniCD = perizia.versioniPerCampo(field.nomeCampo)
        if indiceCorrente < versioniCD.count - 1 {
            // Elimina versioni future da Core Data
            for i in (indiceCorrente + 1)..<versioniCD.count {
                viewContext.delete(versioniCD[i])
            }
            try? viewContext.save()
        }
        
        // Rimuovi versioni future se siamo in mezzo alla cronologia
        if indiceCorrente < versioniCD.count - 1 {
            // Elimina versioni future da Core Data
            for i in (indiceCorrente + 1)..<versioniCD.count {
                viewContext.delete(versioniCD[i])
            }
            try? viewContext.save()
        }
        
        // Salva nuova versione in Core Data
        salvaVersioneInCoreData(field: field, valore: valore)
        
        // Limita a 20 versioni se necessario
        let versioniAggiornate = perizia.versioniPerCampo(field.nomeCampo)
        if versioniAggiornate.count > 20 {
            rimuoviVersioniVecchie(field: field, mantieniUltime: 20)
        }
        
        // Ricarica versioni da Core Data per sincronizzare
        ricaricaVersioniPerCampo(field: field)
    }
    
    private func ricaricaVersioniPerCampo(field: CampoVersione) {
        guard let perizia = perizia else { return }
        
        // Forza refresh
        viewContext.refresh(perizia, mergeChanges: true)
        
        let versioniCD = perizia.versioniPerCampo(field.nomeCampo)
        let contenuti = versioniCD.map { $0.contenuto }
        
        switch field {
        case .relazione:
            versioniRelazione = contenuti
            // Trova l'indice della versione corrente
            if !relazionePerizia.isEmpty {
                if let indice = contenuti.firstIndex(of: relazionePerizia) {
                    indiceVersioneRelazione = indice
                } else {
                    indiceVersioneRelazione = contenuti.count > 0 ? contenuti.count - 1 : -1
                }
            } else {
                indiceVersioneRelazione = contenuti.count > 0 ? contenuti.count - 1 : -1
            }
        case .noteConclusive:
            versioniNoteConclusive = contenuti
            if !noteConclusive.isEmpty {
                if let indice = contenuti.firstIndex(of: noteConclusive) {
                    indiceVersioneNoteConclusive = indice
                } else {
                    indiceVersioneNoteConclusive = contenuti.count > 0 ? contenuti.count - 1 : -1
                }
            } else {
                indiceVersioneNoteConclusive = contenuti.count > 0 ? contenuti.count - 1 : -1
            }
        case .noteRiserva:
            versioniNoteRiserva = contenuti
            if !noteRiserva.isEmpty {
                if let indice = contenuti.firstIndex(of: noteRiserva) {
                    indiceVersioneNoteRiserva = indice
                } else {
                    indiceVersioneNoteRiserva = contenuti.count > 0 ? contenuti.count - 1 : -1
                }
            } else {
                indiceVersioneNoteRiserva = contenuti.count > 0 ? contenuti.count - 1 : -1
            }
        case .noteOsservazioni:
            versioniNoteOsservazioni = contenuti
            if !noteOsservazioni.isEmpty {
                if let indice = contenuti.firstIndex(of: noteOsservazioni) {
                    indiceVersioneNoteOsservazioni = indice
                } else {
                    indiceVersioneNoteOsservazioni = contenuti.count > 0 ? contenuti.count - 1 : -1
                }
            } else {
                indiceVersioneNoteOsservazioni = contenuti.count > 0 ? contenuti.count - 1 : -1
            }
        }
    }
    
    private func salvaVersioneInCoreData(field: CampoVersione, valore: String) {
        guard let perizia = perizia,
              let periziaContext = perizia.managedObjectContext else { return }
        
        let versioniCD = perizia.versioniPerCampo(field.nomeCampo)
        let numeroVersione = Int16(versioniCD.count)
        
        // Usa lo stesso context della perizia per evitare errori di context diversi
        let nuovaVersione = PeriziaVersion(context: periziaContext)
        nuovaVersione.id = UUID()
        nuovaVersione.campo = field.nomeCampo
        nuovaVersione.contenuto = valore
        nuovaVersione.numeroVersione = numeroVersione
        nuovaVersione.dataCreazione = Date()
        nuovaVersione.perizia = perizia
        
        do {
            try periziaContext.save()
        } catch {
            print("[RelazionePeritaleView] Errore salvataggio versione: \(error)")
        }
    }
    
    private func rimuoviVersioniVecchie(field: CampoVersione, mantieniUltime: Int) {
        guard let perizia = perizia,
              let periziaContext = perizia.managedObjectContext else { return }
        
        let versioniCD = perizia.versioniPerCampo(field.nomeCampo)
        if versioniCD.count > mantieniUltime {
            let daEliminare = versioniCD.count - mantieniUltime
            for i in 0..<daEliminare {
                periziaContext.delete(versioniCD[i])
            }
            // Rinumera le versioni rimanenti
            for (index, versione) in versioniCD.suffix(mantieniUltime).enumerated() {
                versione.numeroVersione = Int16(index)
            }
            try? periziaContext.save()
        }
    }
    
    private func navigaVersionePrecedente(field: CampoVersione) {
        switch field {
        case .relazione:
            if indiceVersioneRelazione > 0 {
                indiceVersioneRelazione -= 1
                relazionePerizia = versioniRelazione[indiceVersioneRelazione]
                // Non salvare quando navighi, solo quando modifichi
            }
        case .noteConclusive:
            if indiceVersioneNoteConclusive > 0 {
                indiceVersioneNoteConclusive -= 1
                noteConclusive = versioniNoteConclusive[indiceVersioneNoteConclusive]
            }
        case .noteRiserva:
            if indiceVersioneNoteRiserva > 0 {
                indiceVersioneNoteRiserva -= 1
                noteRiserva = versioniNoteRiserva[indiceVersioneNoteRiserva]
            }
        case .noteOsservazioni:
            if indiceVersioneNoteOsservazioni > 0 {
                indiceVersioneNoteOsservazioni -= 1
                noteOsservazioni = versioniNoteOsservazioni[indiceVersioneNoteOsservazioni]
            }
        }
    }
    
    private func navigaVersioneSuccessiva(field: CampoVersione) {
        switch field {
        case .relazione:
            if indiceVersioneRelazione < versioniRelazione.count - 1 {
                indiceVersioneRelazione += 1
                relazionePerizia = versioniRelazione[indiceVersioneRelazione]
            }
        case .noteConclusive:
            if indiceVersioneNoteConclusive < versioniNoteConclusive.count - 1 {
                indiceVersioneNoteConclusive += 1
                noteConclusive = versioniNoteConclusive[indiceVersioneNoteConclusive]
            }
        case .noteRiserva:
            if indiceVersioneNoteRiserva < versioniNoteRiserva.count - 1 {
                indiceVersioneNoteRiserva += 1
                noteRiserva = versioniNoteRiserva[indiceVersioneNoteRiserva]
            }
        case .noteOsservazioni:
            if indiceVersioneNoteOsservazioni < versioniNoteOsservazioni.count - 1 {
                indiceVersioneNoteOsservazioni += 1
                noteOsservazioni = versioniNoteOsservazioni[indiceVersioneNoteOsservazioni]
            }
        }
    }
    
    private func saveChanges() {
        guard let perizia = perizia else { return }
        
        perizia.relazionePerizia = relazionePerizia.isEmpty ? nil : relazionePerizia
        perizia.noteConclusive = noteConclusive.isEmpty ? nil : noteConclusive
        perizia.noteRiserva = noteRiserva.isEmpty ? nil : noteRiserva
        perizia.noteOsservazioni = noteOsservazioni.isEmpty ? nil : noteOsservazioni
        perizia.hasRiserva = hasRiserva
        perizia.eventoCausatoDa = eventoCausatoDa.isEmpty ? nil : eventoCausatoDa
        perizia.determinazione = determinazione.isEmpty ? nil : determinazione
        
        do {
            try viewContext.save()
        } catch {
            print("[RelazionePeritaleView] Errore salvataggio: \(error)")
        }
    }
