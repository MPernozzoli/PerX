    // MARK: - Helpers UI
    
    private func caratteriColor(_ count: Int, limite: Int) -> Color {
        if count > limite {
            return .red
        } else if count > Int(Double(limite) * 0.9) {
            return .orange
        }
        return .secondary
    }
    
    // MARK: - Generazione
    
    private func generaRelazione() {
        guard let perizia = perizia else { return }
        isGeneratingRelazione = true
        
        Task { @MainActor in
            let relazione = await relazioneService.generaRelazionePeritale(sinistro: sinistro, perizia: perizia)
            self.relazionePerizia = relazione
            self.isGeneratingRelazione = false
            self.saveChanges()
        }
    }
    
    private func miglioraRelazioneConIA() {
        guard !relazionePerizia.isEmpty else { return }
        isGeneratingRelazione = true
        
        Task {
            var migliorata = ""
            
            let result = await PerxiaService.shared.miglioraRelazione(
                relazionePerizia,
                limiteCaratteri: limiteRelazione,
                streamCallback: { chunk in
                    migliorata += chunk
                }
            )
            
            await MainActor.run {
                switch result {
                case .success(let testo):
                    relazionePerizia = testo
                    saveChanges()
                case .failure(let error):
                    print("[RelazionePeritaleView] Errore IA: \(error)")
                }
                isGeneratingRelazione = false
            }
        }
    }
    
    private func generaNoteConclusive() {
        guard let perizia = perizia else { return }
        let note = relazioneService.generaNoteConclusive(sinistro: sinistro, perizia: perizia)
        noteConclusive = note
        saveChanges()
    }
    
    private func generaRiserve() {
        guard let perizia = perizia else { return }
        let riserve = relazioneService.generaRiserve(sinistro: sinistro, perizia: perizia)
        noteRiserva = riserve.joined(separator: "\n")
        saveChanges()
    }
    
    private func generaOsservazioni() {
        guard let perizia = perizia else { return }
        let osservazioni = relazioneService.generaOsservazioni(sinistro: sinistro, perizia: perizia)
        noteOsservazioni = osservazioni.joined(separator: "\n")
        saveChanges()
    }
    
    private func aggiungiRiserva(_ frase: String) {
        guard let perizia = perizia else { return }
        let importoAtto = calcolaImportoAtto()
        let fraseFormattata = relazioneService.formattaFraseRiserva(frase, importoAtto: importoAtto)
        
        if noteRiserva.isEmpty {
            noteRiserva = fraseFormattata
        } else {
            noteRiserva += "\n" + fraseFormattata
        }
        saveChanges()
    }
    
    private func calcolaImportoAtto() -> Double {
        guard let perizia = perizia else { return 0 }
        var totale: Double = 0
        
        for partita in perizia.partiteArray {
            for bene in partita.beniArray {
                if let forzato = bene.liquidazioneForzata {
                    totale += forzato.doubleValue
                } else {
                    for voce in bene.vociCostoArray where voce.indennizzabile {
                        if let vsu = voce.vsu { totale += vsu.doubleValue }
                        if let si = voce.si { totale += si.doubleValue }
                    }
                }
            }
        }
        
        return totale
    }
    
    // MARK: - Load/Save
    
    private func loadValues() {
        guard let perizia = perizia else { return }
        
        relazionePerizia = perizia.relazionePerizia ?? ""
        noteConclusive = perizia.noteConclusive ?? ""
        noteRiserva = perizia.noteRiserva ?? ""
        noteOsservazioni = perizia.noteOsservazioni ?? ""
        hasRiserva = perizia.hasRiserva
        eventoCausatoDa = perizia.eventoCausatoDa ?? ""
        determinazione = perizia.determinazione ?? ""
        
        // EVENTO CAUSATO DA: sempre precompilato se vuoto
        if eventoCausatoDa.isEmpty {
            let defaultEvento = relazioneService.generaEventoCausatoDa(sinistro: sinistro, perizia: perizia)
            if !defaultEvento.isEmpty {
                eventoCausatoDa = defaultEvento
                perizia.eventoCausatoDa = defaultEvento
                try? viewContext.save()
            }
        }
        
        // Carica versioni da Core Data
        caricaVersioniDaCoreData()
        
        // Se determinazione è vuota, prova a derivarla
        if determinazione.isEmpty {
            if let derivata = relazioneService.derivaDeterminazione(da: sinistro) {
                determinazione = derivata
                perizia.determinazione = derivata
                try? viewContext.save()
            }
        }
    }
    
    // MARK: - Generazione Automatica
    
    private func checkAutoGeneration() {
        guard let perizia = perizia else { return }
        
        // Calcola hash della perizia (basato su beni)
        let hashPerizia = calcolaHashPerizia(perizia)
        
        // Se la perizia è compilata (almeno un bene) e non abbiamo ancora generato o è cambiata
        let haBeni = !perizia.partiteArray.isEmpty || !perizia.beniBozzaArray.isEmpty
        
        if haBeni && (!hasAutoGenerated || hashPerizia != lastPeriziaHash) {
            // Genera automaticamente se relazione è vuota
            if relazionePerizia.isEmpty {
                generaRelazione()
            }
            
            hasAutoGenerated = true
            lastPeriziaHash = hashPerizia
        }
    }
    
    private func calcolaHashPerizia(_ perizia: Perizia) -> Int {
        var hash = 0
        for partita in perizia.partiteArray {
            hash ^= partita.beniArray.count.hashValue
            for bene in partita.beniArray {
                hash ^= bene.nome.hashValue
            }
        }
        hash ^= perizia.beniBozzaArray.count.hashValue
        return hash
    }
    
